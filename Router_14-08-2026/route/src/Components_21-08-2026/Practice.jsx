// React Router

// React Router is a library used in React applications to create multiple pages/routes without reloading the entire browser page.

// For example, a website can have:

// / → Home
// /about → About
// /contact → Contact
// /products → Products
// /products/101 → Product details

// React Router changes what component is displayed based on the URL.


// | Concept             | Used in                |
// | ------------------- | ---------------------- |
// | `BrowserRouter`     | Entire application     |
// | `Routes`            | App.jsx                |
// | `Route`             | Every URL              |
// | `Link`              | Student navigation     |
// | `useParams()`       | Student ID             |
// | Dynamic routing     | `/students/:studentId` |
// | Nested routing      | Marks & Attendance     |
// | `Outlet`            | Student profile        |
// | `useSearchParams()` | Student search         |
// | Query parameters    | `/search?name=Rahul`   |
// | `useNavigate()`     | Back/navigation        |
// | `navigate(-1)`      | Browser history        |
// | `*` route           | 404 handling           |

