// Parent to Child Communication in React

// Parent to Child Communication means sending data from a parent component to a child component using Props.

// The Parent Component sends data.
// The Child Component receives the data through props.
// The child displays the received data.
// The same child component can be reused with different props.



// Advantages of Parent to Child Communication
// Makes components reusable.
// Reduces duplicate code.
// Keeps data organized.
// Makes applications easier to maintain.
// Follows React's one-way data flow.
