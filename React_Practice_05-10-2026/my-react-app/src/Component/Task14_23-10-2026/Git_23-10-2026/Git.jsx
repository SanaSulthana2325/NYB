// Git & GitHub – Topics to Learn
// 1. Git Fundamentals – Understand Git version control and how it tracks code changes.
// 2. Repository Creation – Create a Git repository to manage your project files.
// 3. Git Commands – Practice git init, git status, git add, and git commit to initialize a repository, check changes, stage files, and save changes.
// 4. Remote Operations – Learn git push, git pull, and git clone to upload, download, and copy project repositories.
// 5. .gitignore – Specify files and folders Git should ignore, such as node_modules.
// 6. Branches – Create and switch between branches to work on different tasks independently.
// 7. Feature Branches – Develop new features without directly changing the main branch.
// 8. Merge – Combine changes from different branches.
// 9. Pull Requests – Submit code changes for review before merging them into the main branch.
// 10. README Documentation – Create a README.md file explaining the project's purpose, setup, installation, and usage.