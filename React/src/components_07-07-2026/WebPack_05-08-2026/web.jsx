// What is Webpack?

// Webpack is a tool that takes many files (JavaScript, CSS, images, etc.) and combines them into a few optimized files that the browser can understand.

// Without Webpack, a browser may need to load many separate files. With Webpack, it often loads one bundled JavaScript file, making the application faster and easier to manage.



// Why do we need Webpack?

// Suppose your project has:

// index.js

// math.js

// style.css

// logo.png

// A browser cannot directly understand everything the way modern development tools do. Webpack processes these files and creates a production-ready version.

// Simple definition

// Webpack takes all your project files (JS, CSS, images, etc.), processes them, and creates bundled output files that are loaded by the browser efficiently.