// What is useState?

// useState is a React Hook that allows a functional component to store and update data (state).

// Think of state as information that can change while the app is running.

// Examples:

// Counter value

// User name

// Login status

// Theme (light/dark)

// Form input values

// Todo list



// What is useEffect?

// useEffect is a React Hook used for handling side effects in a component.

// A side effect is something your component does outside of simply returning JSX.

// Common examples:

// Calling an API
// Fetching data
// Changing the document title
// Setting a timer
// Adding event listeners
// Reading/writing browser storage


// | `useState`            | `useEffect`             |
// | --------------------- | ----------------------- |
// | Stores data           | Performs side effects   |
// | Updates state         | Runs side-effect code   |
// | Example: counter      | Example: API call       |
// | Example: username     | Example: timer          |
// | Example: login status | Example: event listener |


